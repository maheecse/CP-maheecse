void solve()
{
    ll n, x, y, z, H2, H1, t;
    cin >> n >> x >> y >> z;
    H2 = ceil((double)n / (x + y));
    if ((n - z * x) < 0)
    {
        H1 = z;
    }
    else
    {
        H1 = z + ceil((double)(n - z * x) / (x + 10 * y));
    }
    cout << min(H1, H2) << endl;
}

